const journeyTabs = [...document.querySelectorAll("[data-journey-tab]")];
const journeyPanels = [...document.querySelectorAll("[data-journey-panel]")];

function activateJourney(name) {
  journeyTabs.forEach(tab => {
    const active = tab.dataset.journeyTab === name;
    tab.setAttribute("aria-selected", String(active));
    tab.tabIndex = active ? 0 : -1;
  });
  journeyPanels.forEach(panel => {
    panel.hidden = panel.dataset.journeyPanel !== name;
  });
}

journeyTabs.forEach((tab, index) => {
  tab.addEventListener("click", () => activateJourney(tab.dataset.journeyTab));
  tab.addEventListener("keydown", event => {
    if (!["ArrowLeft", "ArrowRight"].includes(event.key)) return;
    event.preventDefault();
    const direction = event.key === "ArrowRight" ? 1 : -1;
    const next = (index + direction + journeyTabs.length) % journeyTabs.length;
    journeyTabs[next].focus();
    activateJourney(journeyTabs[next].dataset.journeyTab);
  });
});
